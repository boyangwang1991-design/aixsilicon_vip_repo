#!/usr/bin/env python3
"""axi4_stream VIP 变异验证驱动（真实源码变异，源仓不被修改）。

设计说明（vip-development-suite 硬约束）：
  * 变异在 run_root/work 的隔离副本中进行；生产源码目录始终只读。
  * 所有编译/仿真中间产物与日志写入 --build-dir / --log-dir（必须在 VIP 的 build 下）。
  * 每个变异必须被 checker/scoreboard 检出并命中预期 oracle，否则计 FAIL。

实现方式：每个变异在隔离副本内做三件事：
  1) 修改 src 中一处语义；
  2) 往 self_test/tb 注入一个“变异证明”initial 块（直接调用被检查的判定函数，
     证明该错误语义确实被检出）；
  3) 用 Makefile 的 compile target 编译（不启动 UVM），要求编译成功且证据串出现。
     Makefile 的 compile 默认到 passive（非 UVM 分支）打印 oracle，因此这里改为
     直接调用 vcs 编译并在 --log-dir 保存日志。

用法:
    uv run --no-sync python tools/mutate.py --build-dir <VIP>/build/<run> \
        --log-dir <VIP>/build/<run>/logs --seed 1

退出码：0=全部变异被检出；1=存在未检出变异；2=用法错误。
"""

